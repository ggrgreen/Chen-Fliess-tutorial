"""
identifiability.py -- are the coefficients of a truncated Chen-Fliess series determined by input-output data?

Same Duffing set-up and trials as compare_constructions.py (x0 = (0.5, 0.3), multi-sine inputs, 1 ms sampling,
12 training trials).  Ordinary least squares throughout (no ridge, so no bias is added).

  1. Data generated by the truncated series itself (y = sum_w c_w I_w with the exact c_w): if the design has full
     column rank, least squares returns the c_w exactly, up to rounding.  This separates identifiability from the
     error of truncation.
  2. Data from the true Duffing system, no noise: the error is then the truncation error, mapped into the
     coefficients.
  3. Noise: the fitted coefficients have covariance sigma^2 (X^T X)^{-1}.  The predicted standard error of each
     coefficient is compared with the spread over 50 noise draws.
  4. Excitation: the same quantities with larger inputs and with longer windows.
  5. Kernels: h_1(0.1; s) and h_2(0.1; s1, s2) from the fitted coefficients against the exact kernels.
  6. Bases: the same regression in the Radford (Lyndon) basis R_w = prod I_l^n / n!, and with Lyndon words only.

Writes results/identifiability.json.


@author: gary green
last edit 19-10-2026
"""
import os, sys, json, time
