sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np

import cfs_tutorial as G
from cfs_tutorial.signature import sampled_iterated_integrals
from cfs_tutorial.integrate import iterated_integrals
from cfs_tutorial.lyndon import radford_features, is_lyndon
from compare_constructions import duffing, r2, demean, fit as ridge_fit, X0, DT, N_TRIALS, TRAIN, VAL
from duffing_symbolic import duffing_coeffs

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEEDS = 50


def make_input(rng, sd):
    f = rng.uniform(1.0, 15.0, 3); ph = rng.uniform(0, 2 * np.pi, 3); a = rng.normal(0, 1, 3)
    a *= sd / np.sqrt(0.5 * np.sum(a ** 2))
    def u(s):
        s = np.asarray(s, float)
        v = np.sum(a * np.sin(2 * np.pi * f * s[..., None] + ph), axis=-1)
        return v if s.ndim else np.array([v])
    return u


def ols(X, y):
    scale = np.linalg.norm(X, axis=0); Xs = X / scale
    return np.linalg.lstsq(Xs, y, rcond=None)[0] / scale


def by_length(err, words, K):
    return {L: float(np.max(np.abs([e for e, w in zip(err, words) if len(w) == L]))) for L in range(1, K + 1)}


def kernel_errors(cfit, cexact, K, T_k=0.1):
    """Symmetric kernels on the whole interval / square of input times."""
    s1 = np.linspace(0, T_k, 201)[:, None]
    h1f = G.symmetric_kernel(G.extract_kernel_terms(cfit, 1, K), T_k, s1)
    h1e = G.symmetric_kernel(G.extract_kernel_terms(cexact, 1, K), T_k, s1)
    g = np.linspace(0, T_k, 41); S1, S2 = np.meshgrid(g, g, indexing="ij"); S = np.stack([S1, S2], -1).reshape(-1, 2)
    h2f = G.symmetric_kernel(G.extract_kernel_terms(cfit, 2, K), T_k, S)
    h2e = G.symmetric_kernel(G.extract_kernel_terms(cexact, 2, K), T_k, S)
    return dict(h1_err=float(np.max(np.abs(h1f - h1e))), h1_max=float(np.max(np.abs(h1e))),
                h2_err=float(np.max(np.abs(h2f - h2e))), h2_max=float(np.max(np.abs(h2e))))


def tensor_log_lyndon(E, words, K):
    """Log-signature coordinates on Lyndon words: the coefficient of each Lyndon word in log S, S = 1 + sum_w I_w w
    (truncated at K).  These span the same functions as the coordinates in the bracket basis (triangular change)."""
    from cfs_tutorial.lyndon import is_lyndon as isl
    X = {w: E[i] for i, w in enumerate(words)}
    Xk = dict(X); logS = {w: X[w].copy() for w in words}
    for k in range(2, K + 1):
        new = {}
        for w in words:
            if len(w) < k:
                continue
            acc = 0.0
            for j in range(1, len(w)):
                u, v = w[:j], w[j:]
                if u in Xk and len(u) >= k - 1:
                    acc = acc + Xk[u] * X[v]
            new[w] = acc
        Xk = {w: a for w, a in new.items() if not np.isscalar(a)}
        for w, a in Xk.items():
            logS[w] = logS[w] + (-1) ** (k + 1) * a / k
    lyn = [w for w in words if isl(w)]
    return np.array([logS[w] for w in lyn]), lyn


def lie_rank_gap(coef, K):
    from cfs_tutorial.lyndon import lie_hankel_matrix
    H, _, _ = lie_hankel_matrix(coef, 1, K)
    sv = np.linalg.svd(H, compute_uv=False); sv = sv / sv[0]
    lg = np.log10(np.maximum(sv[:-1], 1e-300)) - np.log10(np.maximum(sv[1:], 1e-300))
    j = int(np.argmax(lg))
    return dict(rank=j + 1, gap=float(10 ** lg[j]), n=len(sv))


def experiment(K, T, sd_u, seed_inputs, noises=(0.0, 0.01), n_train=TRAIN):
    t = np.arange(0, T + DT / 2, DT)
    rng = np.random.default_rng(seed_inputs)
    inputs = [make_input(rng, sd_u) for _ in range(N_TRIALS + n_train - TRAIN)]   # extra training trials are drawn after the standard 24
    NT = len(inputs)
    EW = [sampled_iterated_integrals(t, u(t)[..., 0] if np.ndim(u(t)) > 1 else u(t), K) for u in inputs]   # sampled data: iisignature
    words = list(EW[0][1]); E = [e for e, _ in EW]
    Ex = [iterated_integrals(t, u, 1, K)[0] for u in inputs]           # exact integrals, for comparison only
    # sampling error of each column (word), relative to that column's own size over the window, training trials
    exact = dict(duffing_coeffs(order=K, q1_0=X0[0], q2_0=X0[1])); exact[()] = 0.0
    ce = np.array([exact[w] for w in words])
    Y = [duffing(t, u) for u in inputs]
    tr = list(range(TRAIN)) + list(range(N_TRIALS, NT)); va = range(TRAIN, TRAIN + VAL); te = range(TRAIN + VAL, N_TRIALS)
    col_err = [max(np.max(np.abs(E[i][j] - Ex[i][j])) / np.max(np.abs(Ex[i][j])) for i in tr) for j in range(len(words))]
    X = np.hstack(demean([E[i] for i in tr])).T          # one free offset per window
    Xs = X / np.linalg.norm(X, axis=0)
    sv = np.linalg.svd(Xs, compute_uv=False)
    out = dict(K=K, T=T, sd_u=sd_u, n_train=len(tr), n_rows=int(X.shape[0]), n_words=len(words), cond_scaled=float(sv[0] / sv[-1]),
               rank=int(np.sum(sv > sv[0] * X.shape[0] * np.finfo(float).eps)))
    # 1. data from the truncated series itself
    ytr = X @ ce
    out["self_err"] = by_length(ols(X, ytr) - ce, words, K)
    # 2. data from the true system, no noise
    y = np.concatenate(demean([Y[i] for i in tr]))
    c0 = ols(X, y)
    out["noiseless_err"] = by_length(c0 - ce, words, K)
    Xx = np.hstack(demean([Ex[i] for i in tr])).T
    out["noiseless_err_exact_features"] = by_length(ols(Xx, y) - ce, words, K)
    out["column_sampling_err"] = by_length(np.array(col_err), words, K)
    svx = np.linalg.svd(Xx / np.linalg.norm(Xx, axis=0), compute_uv=False)
    out["rank_exact_features"] = int(np.sum(svx > svx[0] * Xx.shape[0] * np.finfo(float).eps)); out["cond_exact_features"] = float(svx[0] / svx[-1])
    out["exact_max"] = by_length(ce, words, K)
    out["noiseless_test_r2"] = float(np.mean([r2(c0 @ E[i], Y[i]) for i in te]))
    out["trunc_test_r2"] = float(np.mean([r2(ce @ E[i], Y[i]) for i in te]))
    cdict = {(): 0.0}; cdict.update(dict(zip(words, c0)))
    out["kernels_noiseless"] = kernel_errors(cdict, exact, K)
    LS = [tensor_log_lyndon(E[i], words, K)[0] for i in range(NT)]
    # 3. noise: predicted standard error against the spread over noise draws
    sdy = float(np.std(np.concatenate([Y[i] for i in tr])))
    XtXi = np.linalg.inv(X.T @ X) if out["rank"] == len(words) else np.linalg.pinv(X.T @ X)
    for nz in noises:
        if nz == 0:
            continue
        sig = nz * sdy
        se_pred = sig * np.sqrt(np.diag(XtXi))
        fits, r2s, kers, lrr2s, lsr2s = [], [], [], [], []
        rfits, rr2s, rkers, lr2s, nooff = [], [], [], [], []
        lyn = [j for j, w in enumerate(words) if is_lyndon(w)]
        for sd in range(SEEDS):
            nrng = np.random.default_rng(1000 * sd + int(nz * 1e4))
            Yn = [(lambda z: z - z[0])(Y[i] + sig * nrng.standard_normal(len(Y[i]))) for i in range(NT)]   # each noisy window shifted to start at zero
            yn = np.concatenate(demean([Yn[i] for i in tr]))
            c = ols(X, yn)
            fits.append(c)
            r2s.append(np.mean([r2(c @ E[i], Y[i]) for i in te]))
            cr = ridge_fit([E[i] for i in tr], [Yn[i] for i in tr], [E[i] for i in va], [Yn[i] for i in va])[0]
            rfits.append(cr)
            cn = ridge_fit([E[i] for i in tr], [Yn[i] for i in tr], [E[i] for i in va], [Yn[i] for i in va], offsets=False)[0]
            nooff.append(np.mean([r2(cn @ E[i], Y[i]) for i in te]))
            rr2s.append(np.mean([r2(cr @ E[i], Y[i]) for i in te]))
            cl = ols(X[:, lyn], yn)
            lr2s.append(np.mean([r2(cl @ E[i][lyn], Y[i]) for i in te]))
            clr = ridge_fit([E[i][lyn] for i in tr], [Yn[i] for i in tr], [E[i][lyn] for i in va], [Yn[i] for i in va])[0]
            lrr2s.append(np.mean([r2(clr @ E[i][lyn], Y[i]) for i in te]))
            cls = ridge_fit([LS[i] for i in tr], [Yn[i] for i in tr], [LS[i] for i in va], [Yn[i] for i in va])[0]
            lsr2s.append(np.mean([r2(cls @ LS[i], Y[i]) for i in te]))
            cd = {(): 0.0}; cd.update(dict(zip(words, c))); kers.append(kernel_errors(cd, exact, K))
            cd = {(): 0.0}; cd.update(dict(zip(words, cr))); rkers.append(kernel_errors(cd, exact, K))
            if sd == 0:
                out[f"lie_fit_{nz:g}"] = lie_rank_gap(cd, K)
                # all kernels of the fitted series together, against the true response, on the first test trial
                i0 = te[0]; ix = np.linspace(len(t) // 5, len(t) - 1, 5).astype(int); tg = t[ix]
                nodes = {0: 1, 1: 40, 2: 30, 3: 20, 4: 14, 5: 10, 6: 8, 7: 6, 8: 5}
                ysum = np.array([sum(G.kernel_contribution(cd, n, K, tt, inputs[i0], n_nodes=nodes[n]) for n in range(K + 1)) for tt in tg])
                out[f"allkernels_fit_{nz:g}"] = dict(max_abs_err=float(np.max(np.abs(ysum - Y[i0][ix]))),
                                                     series_err=float(np.max(np.abs(cr @ E[i0][:, ix] - Y[i0][ix]))),
                                                     max_abs_y=float(np.max(np.abs(Y[i0]))))
        fits = np.array(fits); rfits = np.array(rfits)
        ratio = fits.std(0) / se_pred
        out[f"noise_{nz:g}"] = dict(se_pred=by_length(se_pred, words, K), se_obs=by_length(fits.std(0), words, K),
                                    err=by_length(np.median(np.abs(fits - ce), 0), words, K),
                                    test_r2_median=float(np.median(r2s)),
                                    h1_err_median=float(np.median([k["h1_err"] for k in kers])),
                                    h2_err_median=float(np.median([k["h2_err"] for k in kers])),
                                    h1_max=kers[0]["h1_max"], h2_max=kers[0]["h2_max"],
                                    ridge=dict(err=by_length(np.median(np.abs(rfits - ce), 0), words, K),
                                               test_r2_median=float(np.median(rr2s)),
                                               h1_err_median=float(np.median([k["h1_err"] for k in rkers])),
                                               h2_err_median=float(np.median([k["h2_err"] for k in rkers]))),
                                    lyndon_only_test_r2_median=float(np.median(lr2s)),
                                    lyndon_only_ridge_test_r2_median=float(np.median(lrr2s)),
                                    logsig_ridge_test_r2_median=float(np.median(lsr2s)),
                                    se_ratio=dict(median=float(np.median(ratio)), lo=float(np.min(ratio)), hi=float(np.max(ratio))),
                                    n_kernel_draws=len(kers),
                                    no_offset_ridge_test_r2_median=float(np.median(nooff)))
    # size of the second-order part of the true response for these inputs (exact series)
    if K >= 4:
        o2 = [abs(G.kernel_contribution(exact, 2, K, tt, inputs[i], n_nodes=24)) for i in te for tt in (0.1, 0.125, 0.15) if tt <= T]
        out["order2_part_max"] = float(max(o2))
    out["lie_fit_0"] = lie_rank_gap(cdict, K)
    # 6. bases
    Eall = [np.vstack([np.ones(e.shape[1]), e]) for e in E]; W1 = [()] + words
    Rtr = np.hstack(demean([radford_features(Eall[i], W1)[1:] for i in tr])).T
    Rs = Rtr / np.linalg.norm(Rtr, axis=0); svR = np.linalg.svd(Rs, compute_uv=False)
    dR = ols(Rtr, y)
    Rte = [radford_features(Eall[i], W1)[1:] for i in te]
    out["radford"] = dict(cond_scaled=float(svR[0] / svR[-1]),
                          test_r2=float(np.mean([r2(dR @ R_, Y[i]) for R_, i in zip(Rte, te)])),
                          max_pred_diff_vs_words=float(max(np.max(np.abs(dR @ R_ - c0 @ E[i])) for R_, i in zip(Rte, te))))
    lyn = [j for j, w in enumerate(words) if is_lyndon(w)]
    cl = ols(X[:, lyn], y)
    Xl = X[:, lyn] / np.linalg.norm(X[:, lyn], axis=0); svl = np.linalg.svd(Xl, compute_uv=False)
    out["lyndon_only"] = dict(n=len(lyn), test_r2=float(np.mean([r2(cl @ E[i][lyn], Y[i]) for i in te])),
                              cond_scaled=float(svl[0] / svl[-1]))
    # log-signature on Lyndon words, read out linearly (the readout used with log-signatures in later work)
    XL = np.hstack(demean([LS[i] for i in tr])).T
    XLs = XL / np.linalg.norm(XL, axis=0); svL = np.linalg.svd(XLs, compute_uv=False)
    cL = ols(XL, y)
    va_ = range(TRAIN, TRAIN + VAL)
    cLr = ridge_fit([LS[i] for i in tr], [Y[i] for i in tr], [LS[i] for i in va_], [Y[i] for i in va_])[0]
    clr0 = ridge_fit([E[i][lyn] for i in tr], [Y[i] for i in tr], [E[i][lyn] for i in va_], [Y[i] for i in va_])[0]
    cfr0 = ridge_fit([E[i] for i in tr], [Y[i] for i in tr], [E[i] for i in va_], [Y[i] for i in va_])[0]
    out["ridge_noiseless"] = dict(full=float(np.mean([r2(cfr0 @ E[i], Y[i]) for i in te])),
                                  lyndon_only=float(np.mean([r2(clr0 @ E[i][lyn], Y[i]) for i in te])),
                                  logsig=float(np.mean([r2(cLr @ LS[i], Y[i]) for i in te])))
    out["logsig_linear"] = dict(n=len(LS[0]), cond_scaled=float(svL[0] / svL[-1]),
                                test_r2=float(np.mean([r2(cL @ LS[i], Y[i]) for i in te])))
    return out


if __name__ == "__main__":
    t0 = time.time()
    R = dict(runs=[])
    for K, T, sd_u, ntr in [(4, 0.15, 0.3, 12), (6, 0.15, 0.3, 12), (4, 0.30, 0.3, 12), (6, 0.30, 0.3, 12),
                            (6, 0.15, 1.0, 12), (6, 0.15, 3.0, 12), (6, 0.60, 0.3, 12), (8, 0.15, 0.3, 12), (8, 0.60, 0.3, 12),
                            (6, 0.15, 0.3, 48), (8, 0.15, 0.3, 48)]:
        r = experiment(K, T, sd_u, 100 + K, n_train=ntr)
        R["runs"].append(r)
        print(f"K={K} T={T} sd={sd_u}: cond {r['cond_scaled']:.2e} rank {r['rank']}/{r['n_words']} "
              f"self {max(r['self_err'].values()):.1e} noiseless {r['noiseless_err']} "
              f"noise1% err {r['noise_0.01']['err']} se_pred {r['noise_0.01']['se_pred']} "
              f"R2 {r['noise_0.01']['test_r2_median']:.4f} ridge {r['noise_0.01']['ridge']} lynR2 {r['noise_0.01']['lyndon_only_test_r2_median']:.4f} h1 {r['noise_0.01']['h1_err_median']:.2e}/{r['noise_0.01']['h1_max']:.2e} "
              f"h2 {r['noise_0.01']['h2_err_median']:.2e}/{r['noise_0.01']['h2_max']:.2e} | radford cond {r['radford']['cond_scaled']:.2e} "
              f"diff {r['radford']['max_pred_diff_vs_words']:.1e} | lyndon-only n={r['lyndon_only']['n']} R2 {r['lyndon_only']['test_r2']:.4f} "
              f"({time.time() - t0:.0f}s)", flush=True)
        json.dump(R, open(os.path.join(ROOT, "results", "identifiability.json"), "w"), indent=1)
